    private static string Server() => """
        // <auto-generated />
        import { AsyncLocalStorage } from "node:async_hooks";
        import { baseLocale, requestLocaleStorage, resolveLocale } from "./runtime.js";
        // One storage for the process, shared through the runtime's locale channel: the request locale that one catalog's
        // runWithLocale sets is the locale of every catalog generated by this compiler or a later one, such as a library's.
        const storage = requestLocaleStorage(() => new AsyncLocalStorage());
        export function runWithLocale(locale, operation, options) {
          if (typeof operation !== "function") throw new TypeError("A request operation is required.");
          const resolved = resolveLocale(locale); let requested = resolved;
          // A requested tag that does not resolve to the request's locale is ignored, so the text locale stays the one given.
          if (typeof options?.requestedLocale === "string") { try { if (resolveLocale(options.requestedLocale) === resolved) requested = options.requestedLocale; } catch { /* Invalid or unsupported tag. */ } }
          const timeZone = typeof options?.timeZone === "string" && options.timeZone.length <= 64 ? options.timeZone : undefined;
          // The requested tag (de-CH) formats numbers and dates; every catalog resolves it to its own locale (de).
          return storage.run(Object.freeze({ requested, timeZone }), operation);
        }
        export function getRequestLocale() { const store = storage.getStore(); return typeof store?.requested === "string" ? resolveLocale(store.requested) : baseLocale; }
        """;

