    internal static IReadOnlyList<TranslationGeneratedOutput> Render(Rmf2ProjectV5 project)
    {
        string root = project.Id + ".esm-v5/";
        var messages = project.CanonicalMessages.OrderBy(item => item.Key, StringComparer.Ordinal).ToArray();
        var outputs = new List<TranslationGeneratedOutput>(messages.Length + 10)
        {
            Output(TranslationGeneratedOutputKind.EsmRuntime, root + "runtime.js", "text/javascript", Runtime(project)),
            Output(TranslationGeneratedOutputKind.EsmRuntimeTypes, root + "runtime.d.ts", "text/typescript", RuntimeTypes(project)),
            Output(TranslationGeneratedOutputKind.EsmTransport, root + "transport.js", "text/javascript", Transport(project)),
            Output(TranslationGeneratedOutputKind.EsmTransportTypes, root + "transport.d.ts", "text/typescript", TransportTypes(project)),
            Output(TranslationGeneratedOutputKind.EsmDynamic, root + "dynamic.js", "text/javascript", Dynamic(project)),
            Output(TranslationGeneratedOutputKind.EsmDynamicTypes, root + "dynamic.d.ts", "text/typescript", DynamicTypes(project)),
            Output(TranslationGeneratedOutputKind.EsmServer, root + "server.js", "text/javascript", Server()),
            Output(TranslationGeneratedOutputKind.EsmServerTypes, root + "server.d.ts", "text/typescript", ServerTypes()),
        };
        using (JsonDocument markup = JsonDocument.Parse(project.MarkupContract))
        {
            JsonElement markupMessages = markup.RootElement.TryGetProperty("messages", out JsonElement value) ? value : default;
            foreach (Rmf2MessageContractV5 message in messages)
                outputs.Add(Output(TranslationGeneratedOutputKind.EsmMessage, root + "messages/" + FileName(message.Key),
                    "text/javascript", Message(project, message, markupMessages)));
        }
        outputs.Add(Output(TranslationGeneratedOutputKind.EsmMessageNamespace, root + "messages/_index.js",
            "text/javascript", Namespace(messages)));
        // A module namespace object: bundlers keep only the members an application reads (m.key()).
        outputs.Add(Output(TranslationGeneratedOutputKind.EsmMessagesIndex, root + "messages.js",
            "text/javascript", "// <auto-generated />\nexport * as m from \"./messages/_index.js\";\n"));
        outputs.Add(Output(TranslationGeneratedOutputKind.EsmMessagesTypes, root + "messages.d.ts",
            "text/typescript", MessageTypes(project, messages)));
        outputs.Add(Manifest(project, outputs, root));
        outputs.Sort(static (left, right) => StringComparer.Ordinal.Compare(left.RelativePath, right.RelativePath));
        return outputs;
    }

    private static string Runtime(Rmf2ProjectV5 project)
    {
        var writer = new GenerationWriter();
        writer.Line("// <auto-generated />");
        writer.Line("export const esmAbiVersion = " + TranslationOutputRenderer.EsmAbiVersion + ";");
        writer.Line("export const rmf2RuntimeAbiVersion = " + Rmf2ProjectV5.RuntimeAbiVersion + ";");
        writer.Line("export const messageGrammarVersion = " + Rmf2ProjectV5.MessageGrammarVersion + ";");
        writer.Line("export const profile = " + GenerationSupport.JsonString(Rmf2ProjectV5.Profile) + ";");
        writer.Line("export const generatedNameVersion = " + Rmf2GeneratedNamesV1.Version + ";");
        writer.Line("export const catalog = " + GenerationSupport.JsonString(project.Id) + ";");
        writer.Line("export const contractFingerprint = " + GenerationSupport.JsonString(project.CallerFingerprint) + ";");
        writer.Line("export const sourceHash = " + GenerationSupport.JsonString(project.SourceHash) + ";");
        writer.Line("export const baseLocale = " + GenerationSupport.JsonString(project.DefaultLocale) + ";");
        writer.Line("export const locales = Object.freeze(" + JsonSerializer.Serialize(project.Locales.Select(item => item.Tag).OrderBy(item => item, StringComparer.Ordinal)) + ");");
        writer.Line("const unsupportedLocalePolicy = " + GenerationSupport.JsonString(project.UnsupportedLocale.ToString()) + ";");
        // Only the CLDR data of the catalog's languages is embedded.
        writer.Line(TranslationCapabilityRegistry.EsmLocaleSource(project.Locales.Select(item => item.Tag)));
        // Only the markup contracts: per-message contracts live in the message modules and dynamic.js.
        writer.Line("const markupContracts = freezeTrusted(JSON.parse(" + GenerationSupport.JsonString(MarkupContractsJson(project)) + "));");
        // The renderers' table of structured messages; a function, so a bundle without a renderer drops it.
        writer.Line("function structuredMessageTable() { return JSON.parse(" + GenerationSupport.JsonString(StructuredMessagesJson(project)) + "); }");
        // getMessageLocale's table of every message's fallback content locales; a function, so a bundle that never calls it drops it.
        writer.Line("function messageLocaleTable() { return JSON.parse(" + GenerationSupport.JsonString(MessageLocalesJson(project)) + "); }");
        using Stream stream = typeof(Rmf2EsmOutputRendererV5).Assembly.GetManifestResourceStream("Runic.Translations.Compiler.Generation.Rmf2EsmRuntimeV5.js")!;
        using var reader = new StreamReader(stream);
        writer.Line(reader.ReadToEnd());
        return writer.ToString();
    }

    private static string ContractsJson(Rmf2ProjectV5 project, bool includeExtras)
    {
        using var stream = new MemoryStream();
        using (var writer = new Utf8JsonWriter(stream))
        {
            writer.WriteStartObject();
            IEnumerable<Rmf2MessageContractV5> messages = includeExtras
                ? project.CanonicalMessages.Concat(project.ExtraMessages)
                : project.CanonicalMessages;
            foreach (Rmf2MessageContractV5 message in messages.OrderBy(item => item.Key, StringComparer.Ordinal))
            {
                writer.WriteStartObject(message.Key); writer.WriteBoolean("structured", message.Structured); writer.WriteStartArray("inputs");
                foreach (Rmf2InputV5 input in message.Inputs) { writer.WriteStartObject(); writer.WriteString("name", input.Name); writer.WriteString("type", input.Type); writer.WriteEndObject(); }
                writer.WriteEndArray(); writer.WriteEndObject();
            }
            writer.WriteEndObject();
        }
        return Encoding.UTF8.GetString(stream.ToArray());
    }

    private static string MarkupContractsJson(Rmf2ProjectV5 project)
    {
        using JsonDocument markup = JsonDocument.Parse(project.MarkupContract);
        return markup.RootElement.TryGetProperty("contracts", out JsonElement contracts) ? contracts.GetRawText() : "{}";
    }

    // Each structured message (canonical or extra) by key: its slots, and its content kind when it is a document. This is
    // what a renderer checks content against, so it comes from the catalog and not from the message modules.
    private static string StructuredMessagesJson(Rmf2ProjectV5 project)
    {
        using JsonDocument markup = JsonDocument.Parse(project.MarkupContract);
        using var stream = new MemoryStream();
        using (var writer = new Utf8JsonWriter(stream))
        {
            writer.WriteStartObject();
            if (markup.RootElement.TryGetProperty("messages", out JsonElement messages))
                foreach (System.Text.Json.JsonProperty message in messages.EnumerateObject())
                {
                    if (!message.Value.TryGetProperty("structured", out JsonElement structured) || !structured.GetBoolean()) continue;
                    writer.WriteStartObject(message.Name);
                    if (message.Value.TryGetProperty("content", out JsonElement content) && content.GetString() != Rmf2DocumentProfileV5.Inline) { writer.WritePropertyName("content"); content.WriteTo(writer); }
                    writer.WritePropertyName("slots"); message.Value.GetProperty("slots").WriteTo(writer);
                    writer.WriteEndObject();
                }
            writer.WriteEndObject();
        }
        return Encoding.UTF8.GetString(stream.ToArray());
    }

    // Each message (canonical or extra) by key: the locales whose text comes from another locale, with that content locale.
    // A message every locale translates itself maps to an empty object.
    private static string MessageLocalesJson(Rmf2ProjectV5 project)
    {
        using JsonDocument markup = JsonDocument.Parse(project.MarkupContract);
        JsonElement messages = markup.RootElement.TryGetProperty("messages", out JsonElement value) ? value : default;
        using var stream = new MemoryStream();
        using (var writer = new Utf8JsonWriter(stream))
        {
            writer.WriteStartObject();
            foreach (Rmf2MessageContractV5 message in project.CanonicalMessages.Concat(project.ExtraMessages).OrderBy(item => item.Key, StringComparer.Ordinal))
            {
                if (messages.ValueKind != JsonValueKind.Object || !messages.TryGetProperty(message.Key, out JsonElement entry)) continue;
                writer.WriteStartObject(message.Key);
                if (entry.TryGetProperty("contentLocales", out JsonElement contentLocales))
                    foreach (System.Text.Json.JsonProperty locale in contentLocales.EnumerateObject())
                        if (locale.Value.GetString() != locale.Name) writer.WriteString(locale.Name, locale.Value.GetString());
                writer.WriteEndObject();
            }
            writer.WriteEndObject();
        }
        return Encoding.UTF8.GetString(stream.ToArray());
    }

    // One message's contract for the freeze functions: key, structured and inputs, and the markup facts that differ from an
    // inline message without slots (content, slots, skeletons) as the catalog's markup contract states them.
    private static string MessageContractJson(Rmf2MessageContractV5 message, JsonElement markupMessages)
    {
        using var stream = new MemoryStream();
        using (var writer = new Utf8JsonWriter(stream))
        {
            writer.WriteStartObject();
            writer.WriteString("key", message.Key); writer.WriteBoolean("structured", message.Structured); writer.WriteStartArray("inputs");
            foreach (Rmf2InputV5 input in message.Inputs) { writer.WriteStartObject(); writer.WriteString("name", input.Name); writer.WriteString("type", input.Type); writer.WriteEndObject(); }
            writer.WriteEndArray();
            if (markupMessages.ValueKind == JsonValueKind.Object && markupMessages.TryGetProperty(message.Key, out JsonElement markup))
            {
                if (markup.TryGetProperty("content", out JsonElement content) && content.GetString() != Rmf2DocumentProfileV5.Inline) { writer.WritePropertyName("content"); content.WriteTo(writer); }
                if (markup.TryGetProperty("slots", out JsonElement slots) && slots.EnumerateObject().Any()) { writer.WritePropertyName("slots"); slots.WriteTo(writer); }
                if (markup.TryGetProperty("skeletons", out JsonElement skeletons) && skeletons.GetArrayLength() != 0) { writer.WritePropertyName("skeletons"); skeletons.WriteTo(writer); }
            }
            writer.WriteEndObject();
        }
        return Encoding.UTF8.GetString(stream.ToArray());
    }

    // Each locale's message is compact: a message that is one piece of text with no inputs is the text itself
    // (freezeGeneratedText builds the same AST), other messages are minified AST JSON, and a locale whose message
    // comes from its fallback shares that locale's object instead of repeating it.
    // The data sits in a pure call, so a bundler drops a message module whose function the application never calls.
    private static string Message(Rmf2ProjectV5 project, Rmf2MessageContractV5 contract, JsonElement markupMessages)
    {
        var writer = new GenerationWriter();
        writer.Line("// <auto-generated />");
        writer.Line("import { formatCompiledMessage, freezeGeneratedMessage, freezeGeneratedPattern, freezeGeneratedText, getRequestedLocale, resolveLocale } from \"../runtime.js\";");
        writer.Line("const messages = /* @__PURE__ */ (() => {"); writer.Indent();
        writer.Line("const contract = JSON.parse(" + GenerationSupport.JsonString(MessageContractJson(contract, markupMessages)) + ");");
        writer.Line("const messages = Object.create(null);");
        Rmf2LocaleV5[] locales = project.Locales.OrderBy(item => item.Tag, StringComparer.Ordinal).ToArray();
        var resources = locales.ToDictionary(locale => locale.Tag, locale => locale.ResolvedResources.Single(item => item.Key == contract.Key), StringComparer.Ordinal);
        var shared = new List<(string Locale, string Owner)>();
        foreach (Rmf2LocaleV5 locale in locales)
        {
            Rmf2TranslationV5 resource = resources[locale.Tag];
            // The message of another locale, resolved through the fallback chain, is that locale's object.
            if (resource.ContentLocale != locale.Tag && resources.TryGetValue(resource.ContentLocale, out Rmf2TranslationV5? owner) &&
                owner.ContentLocale == resource.ContentLocale && SameMessage(owner, resource, contract))
            {
                shared.Add((locale.Tag, resource.ContentLocale));
                continue;
            }
            string key = "contract", contentLocale = GenerationSupport.JsonString(resource.ContentLocale);
            List<object>? parts = Pattern(resource.Message, contract);
            string value = parts is null
                ? "freezeGeneratedMessage(" + key + ", JSON.parse(" + GenerationSupport.JsonString("{\"contentLocale\":" + contentLocale + ",\"ast\":" +
                    Rmf2MessageJsonV5.Serialize(resource.Message with { Inputs = contract.Inputs }, indented: false) + "}") + "))"
                : parts.Count == 0 || parts is [string]
                    ? "freezeGeneratedText(" + key + ", " + contentLocale + ", " + GenerationSupport.JsonString(parts.Count == 0 ? "" : (string)parts[0]) + ")"
                    : "freezeGeneratedPattern(" + key + ", " + contentLocale + ", [" + string.Join(", ", parts.Select(part => part is string text
                        ? GenerationSupport.JsonString(text) : "[" + GenerationSupport.JsonString(((Rmf2InputV5)part).Name) + "]")) + "])";
            writer.Line("messages[" + GenerationSupport.JsonString(locale.Tag) + "] = " + value + ";");
        }
        foreach ((string locale, string owner) in shared)
            writer.Line("messages[" + GenerationSupport.JsonString(locale) + "] = messages[" + GenerationSupport.JsonString(owner) + "];");
        writer.Line("return Object.freeze(messages);");
        writer.Unindent(); writer.Line("})();");
        string identifier = Rmf2GeneratedNamesV1.Identifier(contract.Key);
        writer.Line("export function " + identifier + "(" + (contract.Inputs.Count == 0 ? "options" : "inputs, options") + ") {"); writer.Indent();
        if (contract.Inputs.Count == 0) writer.Line("const inputs = Object.create(null);");
        // The requested tag (de-CH) chooses the formatting locale of numbers and dates; the catalog locale (de) the text.
        writer.Line("const requested = options?.locale ?? getRequestedLocale(), locale = resolveLocale(requested);");
        writer.Line("return formatCompiledMessage(" + GenerationSupport.JsonString(contract.Key) + ", messages[locale], inputs, requested, locale);");
        writer.Unindent(); writer.Line("}");
        return writer.ToString();
    }


    // A message that is one variant of text and plain input placeholders ({$name} with no function), as text and
    // contract inputs in order; null for any other message. Its AST is what freezeGeneratedPattern rebuilds.
    private static List<object>? Pattern(Rmf2MessageV5 message, Rmf2MessageContractV5 contract)
    {
        if (message.Declarations.Count != 0 || message.Selectors.Count != 0 || message.Variants.Count != 1 || message.Variants[0].Keys.Count != 0) return null;
        var parts = new List<object>();
        foreach (Rmf2NodeV5 node in message.Variants[0].Nodes)
        {
            if (node is Rmf2TextV5 text) { parts.Add(text.Value); continue; }
            if (node is not Rmf2ExpressionNodeV5 { Expression: { Operand.Kind: "input", Function: null, Options.Count: 0, Annotations.Count: 0 } expression }) return null;
            Rmf2InputV5? input = contract.Inputs.SingleOrDefault(item => item.Name == expression.Operand.Value);
            if (input is null || input.Type != expression.ValueType) return null;
            parts.Add(input);
        }
        return parts;
    }

    private static bool SameMessage(Rmf2TranslationV5 left, Rmf2TranslationV5 right, Rmf2MessageContractV5 contract) =>
        ReferenceEquals(left, right) || ReferenceEquals(left.Message, right.Message) ||
        Rmf2MessageJsonV5.Serialize(left.Message with { Inputs = contract.Inputs }, indented: false) ==
        Rmf2MessageJsonV5.Serialize(right.Message with { Inputs = contract.Inputs }, indented: false);

    private static string Namespace(IReadOnlyList<Rmf2MessageContractV5> messages)
    {
        // messages.js exports this module as the namespace m. A key that is not an ASCII identifier is an ES2022 string
        // export name; plain keys stay identifiers so older build targets accept the common case.
        var writer = new GenerationWriter(); writer.Line("// <auto-generated />");
        foreach (Rmf2MessageContractV5 message in messages)
            writer.Line("export { " + Rmf2GeneratedNamesV1.Identifier(message.Key) + " as " + ExportName(message.Key) + " } from \"./" + FileName(message.Key) + "\";");
        return writer.ToString();
    }

