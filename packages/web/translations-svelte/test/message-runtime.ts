// The part of a generated runtime that useMessageLocale relies on: one module-level resolver, read while a message
// formats, as configureLocaleResolver, getLocale and the m.*() functions in generated runtime.js do.
let resolver: () => string = () => "en";

export function configureLocaleResolver(next: () => string): () => void {
  const previous = resolver;
  resolver = next;
  return () => { if (resolver === next) resolver = previous; };
}

export const getLocale = (): string => (["en", "de"].includes(resolver()) ? resolver() : "en");
// The text the message functions format; a test edits it as the dev server swaps an edited message's table in.
export const texts: Record<string, string> = { "title.en": "Title", "title.de": "Titel", "empty.en": "No rows", "empty.de": "Keine Zeilen" };
export const m = {
  title: () => texts[`title.${getLocale()}`]!,
  count: (inputs: { count: number }) => `${inputs.count} ${getLocale() === "de" ? "Einträge" : "entries"}`,
};

// A library catalog's runtime without a resolver of its own: it reads the generated runtimes' shared locale channel, as
// every runtime generated by Runic Translations 0.9 or later does.
function sharedLocale(): string {
  const channel = (globalThis as Record<symbol, { resolver?: (() => string) | null } | undefined>)[Symbol.for("runic.translations.locale")];
  return typeof channel?.resolver === "function" ? channel.resolver() : "en";
}
export const library = {
  empty: () => texts[sharedLocale().startsWith("de") ? "empty.de" : "empty.en"]!,
  requested: () => sharedLocale(),
};
