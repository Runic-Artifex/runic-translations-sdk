test("a dev server makes message modules self-accepting and sends one js-update per edited message", async () => {
  const root = await mkdtemp(join(tmpdir(), "runic-vite-hmr-server-"));
  let server;
  try {
    const generated = join(root, "app.esm-v5"), source = join(root, "en.rmf2");
    const manifest = await writeCatalog(generated, { messages: { title: { en: "Hello", de: "Hallo" }, other: { en: "Other", de: "Andere" } } });
    await writeFile(source, "title = Hello\n");
    await writeFile(join(root, "main.js"), "import { m } from 'virtual:runic-translations/app'; export const title = () => m.title();\n");
    server = await createServer({
      configFile: false, root, logLevel: "silent", appType: "custom",
      server: { middlewareMode: true, ws: false, watch: null },
      plugins: [runicTranslations({ manifest, sourceFiles: [source], typeDeclarations: false })],
    });
    const client = server.environments.client;
    const sent = [];
    const send = client.hot.send.bind(client.hot);
    client.hot.send = payload => { sent.push(payload); return send(payload); };
    await client.transformRequest("/main.js");
    await client.transformRequest("virtual:runic-translations/app");
    const real = await realpath(generated);
    const title = join(real, "messages", `r_${hex("title")}.js`), runtime = join(real, "runtime.js");
    const url = async path => `/${relative(await realpath(root), path).split("\\").join("/")}`;
    for (const path of [join(real, "messages.js"), join(real, "messages", "_index.js"), title, join(real, "messages", `r_${hex("other")}.js`), runtime])
      await client.transformRequest(await url(path));
    const transformed = await client.transformRequest(await url(title));
    assert.match(transformed.code, /import\.meta\.hot\.accept\(\)/);
    assert.match(transformed.code, /__x00__runic-translations:hmr/);
    const [titleModule] = client.moduleGraph.getModulesByFile(title);
    assert.equal(titleModule.isSelfAccepting, true);
    // The dev client is served as a module.
    assert.match((await client.transformRequest("virtual:runic-translations:hmr")).code, /runic\.translations\.text/);

    // The owning build regenerates; the source save then reaches hotUpdate.
    await writeCatalog(generated, { messages: { title: { en: "Hi", de: "Hallo" }, other: { en: "Other", de: "Andere" } } });
    server.watcher.emit("change", source);
    for (let attempt = 0; attempt < 100 && sent.length === 0; attempt++) await new Promise(resolveDelay => setTimeout(resolveDelay, 20));
    assert.equal(sent.length, 1, JSON.stringify(sent));
    assert.equal(sent[0].type, "update");
    assert.deepEqual(sent[0].updates.map(update => [update.type, update.path, update.acceptedPath]),
      [["js-update", titleModule.url, titleModule.url]]);
    const [runtimeModule] = client.moduleGraph.getModulesByFile(runtime);
    assert.equal(runtimeModule.lastHMRTimestamp, 0, "the runtime keeps its URL and instance");

    // An added message reloads.
    sent.length = 0;
    await writeCatalog(generated, { messages: { title: { en: "Hi", de: "Hallo" }, other: { en: "Other", de: "Andere" }, added: { en: "New", de: "Neu" } } });
    server.watcher.emit("change", source);
    for (let attempt = 0; attempt < 100 && sent.length === 0; attempt++) await new Promise(resolveDelay => setTimeout(resolveDelay, 20));
    assert.deepEqual(sent, [{ type: "full-reload", path: "*" }]);
  } finally {
    await server?.close();
    await rm(root, { recursive: true, force: true });
  }
});

// The production identity: a build with the plugin is byte-for-byte the build of the generated files re-exported as the
// plugin's virtual modules always were (the 0.11 plugin's build path), and holds no development code.
test("a production build is byte-identical to the plain re-export of the generated catalog", async () => {
  const root = await mkdtemp(join(tmpdir(), "runic-vite-hmr-production-"));
  try {
    const generated = join(root, "app.esm-v5");
    const manifest = await writeCatalog(generated, { messages: { title: { en: "Hello", de: "Hallo" }, other: { en: "Other", de: "Andere" } } });
    await writeFile(join(root, "main.js"), "import { m } from 'virtual:runic-translations/app';\nimport { locales } from 'virtual:runic-translations/app/runtime';\nexport const text = () => [m.title(), locales.join()].join('|');\n");
    const real = await realpath(generated);
    // What the plugin's build path does: resolve the virtual IDs and re-export the generated entry points.
    const reference = {
      name: "reference-re-export",
      resolveId: id => id === "virtual:runic-translations/app" ? "\0virtual:runic-translations/app/messages"
        : id === "virtual:runic-translations/app/runtime" ? "\0virtual:runic-translations/app/runtime" : null,
      load: id => id === "\0virtual:runic-translations/app/messages" ? `export * from ${JSON.stringify(join(real, "messages.js"))};\n`
        : id === "\0virtual:runic-translations/app/runtime" ? `export * from ${JSON.stringify(join(real, "runtime.js"))};\n` : null,
    };
    const bundle = async (name, plugin) => {
      const outDir = join(root, name);
      await build({ configFile: false, root, logLevel: "silent", mode: "production", plugins: [plugin],
        build: { outDir, minify: false, lib: { entry: join(root, "main.js"), formats: ["es"], fileName: () => "bundle.js" } } });
      const files = (await readdir(outDir, { recursive: true })).sort();
      return Object.fromEntries(await Promise.all(files.map(async file => [file, await readFile(join(outDir, file), "utf8")])));
    };
    const withPlugin = await bundle("plugin", runicTranslations({ manifest, typeDeclarations: false }));
    const plain = await bundle("reference", reference);
    assert.deepEqual(withPlugin, plain);
    assert.deepEqual(await bundle("plugin-again", runicTranslations({ manifest, typeDeclarations: false })), withPlugin);
    for (const marker of ["import.meta.hot", "runicMessageSetters", "runic.translations.text", "runic-translations:hmr", "let   messages"])
      assert.ok(!withPlugin["bundle.js"].includes(marker), marker);
    assert.match(withPlugin["bundle.js"], /Hello/);
    assert.doesNotMatch(withPlugin["bundle.js"], /Other/, "tree-shaking still drops the uncalled message");
  } finally { await rm(root, { recursive: true, force: true }); }
});
