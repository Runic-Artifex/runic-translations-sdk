// Runs the dev client in a sandbox: a browser (window, location, Vite's hot context) or a server-side runner (neither).
function loadDevClient({ browser }) {
  const handlers = new Map(), reloads = [], timers = [], logged = [];
  const hot = { on: (event, handler) => handlers.set(event, handler) };
  const context = vm.createContext({
    Symbol, Set, setTimeout: callback => timers.push(callback),
    console: { info: message => logged.push(message), error: error => logged.push(String(error)) },
    ...(browser ? { window: {}, document: {}, location: { reload: () => reloads.push(1) } } : {}),
  });
  context.globalThis = context;
  // The module as a function of its hot context that returns its export.
  const source = devClientCode.replaceAll("import.meta.hot", "hot").replace("export function textChanged", "function textChanged");
  const textChanged = vm.runInContext(`(hot => {\n${source}\nreturn textChanged;\n})`, context)(hot);
  const channel = context[Symbol.for("runic.translations.text")];
  return { textChanged, channel, reloads, timers, logged, afterUpdate: () => handlers.get("vite:afterUpdate")?.() };
}

test("the dev client bumps the text-change channel once per update and reloads when nothing listens", () => {
  const page = loadDevClient({ browser: true });
  assert.equal(page.channel.version, 1);
  assert.equal(page.channel.revision, 0);
  const seen = [];
  page.channel.listeners.add(() => seen.push(page.channel.revision));
  page.channel.listeners.add(() => { throw new Error("a failing listener"); });
  page.channel.listeners.add(() => seen.push("second"));
  // Three modules of one update payload report a change: one notification after the update.
  page.textChanged(); page.textChanged(); page.textChanged();
  assert.deepEqual(seen, []);
  page.afterUpdate();
  assert.deepEqual(seen, [1, "second"], "listeners run after the revision is incremented; a failing one does not stop the others");
  assert.match(page.logged.join("\n"), /a failing listener/);
  page.afterUpdate();
  assert.equal(page.channel.revision, 1, "an update without a text change does not notify");
  assert.deepEqual(page.reloads, []);

  // Nothing listens: the page reloads rather than showing stale text.
  const bare = loadDevClient({ browser: true });
  bare.textChanged();
  bare.afterUpdate();
  assert.equal(bare.reloads.length, 1);
  assert.match(bare.logged.join("\n"), /page reload: nothing on this page follows text changes/);

  // An existing channel (created by a consumer first) is kept, with its listeners.
  const consumer = loadDevClient({ browser: true });
  assert.ok(consumer.channel.listeners instanceof Set);

  // A server-side runner flushes on a timer and never reloads.
  const server = loadDevClient({ browser: false });
  const calls = [];
  server.channel.listeners.add(() => calls.push(server.channel.revision));
  server.textChanged(); server.textChanged();
  assert.equal(server.timers.length, 1);
  server.timers[0]();
  assert.deepEqual(calls, [1]);
  const lonely = loadDevClient({ browser: false });
  lonely.textChanged(); lonely.timers[0]();
  assert.equal(lonely.reloads.length, 0);
});

