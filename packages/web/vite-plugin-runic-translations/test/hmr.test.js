const fingerprint = `sha256:${"a".repeat(64)}`;
const hex = key => Buffer.from(key, "utf8").toString("hex");
const sha256 = text => createHash("sha256").update(text).digest("hex");
let hotTimestamp = 0;

// A message module as Rmf2EsmOutputRendererV5.Message writes it.
function messageModule(key, texts) {
  return `// <auto-generated />
import { formatMessage, freezeGeneratedMessage, freezeGeneratedPattern, freezeGeneratedText } from "../runtime.js";
${messagesAnchor}
    const contract = JSON.parse(${JSON.stringify(JSON.stringify({ key, structured: false, inputs: [] }))});
    const messages = Object.create(null);
${Object.entries(texts).map(([locale, text]) => `    messages[${JSON.stringify(locale)}] = freezeGeneratedText(contract, ${JSON.stringify(locale)}, ${JSON.stringify(text)});`).join("\n")}
    return Object.freeze(messages);
})();
export function r_${hex(key)}(options) {
    return formatMessage(${JSON.stringify(key)}, messages, Object.create(null), options);
}
`;
}

// A generated catalog in the compiler's layout. `sourceHash` follows the messages, as the compiler's does; `contract`
// stands for anything the catalog's contract tables hold beyond the text.
async function writeCatalog(root, { catalog = "app", messages, contract = "", runtimeExtra = "", moduleOverrides = {} }) {
  await rm(join(root, "messages"), { recursive: true, force: true });
  await mkdir(join(root, "messages"), { recursive: true });
  const keys = Object.keys(messages).sort();
  const sourceHash = `sha256:${sha256(JSON.stringify(messages))}`;
  for (const key of keys) await writeFile(join(root, "messages", `r_${hex(key)}.js`), moduleOverrides[key] ?? messageModule(key, messages[key]));
  await writeFile(join(root, "messages", "_index.js"), `// <auto-generated />\n${keys.map(key => `export { r_${hex(key)} as ${key} } from "./r_${hex(key)}.js";`).join("\n")}\n`);
  await writeFile(join(root, "messages.js"), "// <auto-generated />\nexport * as m from \"./messages/_index.js\";\n");
  await writeFile(join(root, "messages.d.ts"), `import type { MessageOptions } from "./runtime.js";\nexport declare const m: Readonly<{\n${keys.map(key => `  /** ${messages[key].en} */\n  readonly "${key}": (options?: MessageOptions) => string;`).join("\n")}\n}>;\n`);
  await writeFile(join(root, "runtime.js"), `export const esmAbiVersion = 4;
export const rmf2RuntimeAbiVersion = 3;
export const messageGrammarVersion = 5;
export const profile = "rmf2-execution-v2";
export const generatedNameVersion = 1;
export const catalog = ${JSON.stringify(catalog)};
export const contractFingerprint = ${JSON.stringify(fingerprint)};
export const sourceHash = ${JSON.stringify(sourceHash)};
export const locales = Object.freeze(["de","en"]);
${runtimeExtra}export function freezeGeneratedText(contract, locale, text) { return Object.freeze({ locale, text }); }
export function formatMessage(key, messages, inputs, options) {
  const locale = options?.locale ?? globalThis.runicLocale ?? "en";
  return (messages[locale] ?? messages.en).text;
}
export const freezeGeneratedMessage = freezeGeneratedText, freezeGeneratedPattern = freezeGeneratedText;
`);
  await writeFile(join(root, "runtime.d.ts"), "export type MessageOptions = Readonly<{ locale?: string }>;\n");
  for (const name of ["server", "transport"]) {
    await writeFile(join(root, `${name}.js`), "export {};\n");
    await writeFile(join(root, `${name}.d.ts`), "export {};\n");
  }
  await writeFile(join(root, "dynamic.js"), `export const contract = ${JSON.stringify(contract)};\n`);
  await writeFile(join(root, "dynamic.d.ts"), "export {};\n");
  const files = (await readdir(root, { recursive: true })).map(path => path.split("\\").join("/"))
    .filter(path => /\.(?:js|d\.ts)$/.test(path)).sort();
  const assets = await Promise.all(files.map(async path => {
    const content = await readFile(join(root, path));
    return { path, sha256: sha256(content), byteLength: content.byteLength, mediaType: path.endsWith(".d.ts") ? "text/typescript" : "text/javascript" };
  }));
  const manifest = join(root, "web-module-manifest-v3.json");
  await writeFile(manifest, JSON.stringify({
    webModuleManifestVersion: 3, esmAbiVersion: 4, rmf2RuntimeAbiVersion: 3, messageGrammarVersion: 5, profile: "rmf2-execution-v2",
    generatedNameVersion: 1, catalog, contractFingerprint: fingerprint, sourceHash,
    entrypoints: { messages: "messages.js", types: "messages.d.ts", runtime: "runtime.js", server: "server.js", transport: "transport.js", dynamic: "dynamic.js" },
    assets,
  }));
  return manifest;
}

// One Vite environment's module graph and hot channel, recording what the plugin does with them.
function environment(name) {
  const modules = new Map();
  const moduleFor = id => { if (!modules.has(id)) modules.set(id, { id, environment: name }); return modules.get(id); };
  return {
    name, invalidated: [], sent: [],
    moduleGraph: {
      getModuleById: id => moduleFor(id),
      getModulesByFile: file => new Set([moduleFor(file)]),
      invalidateModule(module, seen, timestamp, isHmr) { this.owner.invalidated.push({ id: module.id, timestamp, isHmr }); },
    },
    hot: { send(payload) { this.owner.sent.push(payload); } },
  };
}
function environments() {
  const result = [environment("client"), environment("ssr")];
  for (const item of result) { item.moduleGraph.owner = item; item.hot.owner = item; }
  return result;
}

// Calls hotUpdate as Vite does for one change: the client environment first, then the others, with one timestamp.
async function save(plugin, file, targets) {
  const timestamp = ++hotTimestamp;
  const results = [];
  for (const target of targets)
    results.push(await plugin.hotUpdate.call({ environment: target }, { type: "update", file, timestamp, modules: [], read: async () => "" })
      .then(value => ({ value }), error => ({ error })));
  return { timestamp, results };
}

async function devPlugin(root, options = {}) {
  const generated = join(root, "app.esm-v5");
  const manifest = await writeCatalog(generated, { messages: { title: { en: "Hello", de: "Hallo" }, other: { en: "Other", de: "Andere" } }, ...options });
  const plugin = runicTranslations({ manifest, typeDeclarations: false });
  const logged = [];
  plugin.configResolved({ logger: { info: message => logged.push(message), warn: message => logged.push(message) }, mode: "development" });
  const watcher = new EventEmitter(), sent = [];
  watcher.add = () => {};
  plugin.configureServer({ watcher, httpServer: new EventEmitter(), ws: { send: payload => sent.push(payload) }, moduleGraph: environment("mixed").moduleGraph });
  await plugin.buildStart.call({ addWatchFile() {} });
  const real = await realpath(generated);
  return { plugin, generated, manifest, logged, sent, module: key => join(real, "messages", `r_${hex(key)}.js`) };
}

const snapshot = (files, runtime = "r", catalog = "app") => ({
  catalog, runtime, files: new Map(Object.entries(files)), paths: new Map(Object.keys(files).map(path => [path, `/out/${path}`])),
});

test("the classifier updates text in place and reloads for anything structural", () => {
  const base = { "messages/r_74.js": "1", "messages/r_75.js": "2", "messages/_index.js": "i", "messages.d.ts": "d", "runtime.js": "x", "dynamic.js": "c", "transport.js": "t" };
  const cases = [
    ["text of one message (sourceHash changed too)", { ...base, "messages/r_74.js": "1b", "runtime.js": "y" }, "r", { kind: "in-place", modules: ["/out/messages/r_74.js"] }],
    ["text of two messages", { ...base, "messages/r_74.js": "1b", "messages/r_75.js": "2b" }, "r", { kind: "in-place", modules: ["/out/messages/r_74.js", "/out/messages/r_75.js"] }],
    ["declarations only", { ...base, "messages.d.ts": "d2" }, "r", { kind: "none" }],
    ["nothing", base, "r", { kind: "none" }],
    ["a message added", { ...base, "messages/r_76.js": "3", "messages/_index.js": "i2" }, "r", /messages were added, removed or renamed in catalog 'app'/],
    ["a message removed", Object.fromEntries(Object.entries(base).filter(([path]) => path !== "messages/r_75.js")), "r", /messages were added, removed or renamed/],
    ["the contract (dynamic.js)", { ...base, "messages/r_74.js": "1b", "dynamic.js": "c2" }, "r", /dynamic\.js of catalog 'app' changed \(the catalog's contract changed\)/],
    ["transport.js", { ...base, "transport.js": "t2" }, "r", /transport\.js of catalog 'app' changed/],
    ["_index.js", { ...base, "messages/_index.js": "i2" }, "r", /messages\/_index\.js of catalog 'app' changed/],
    ["the runtime beyond sourceHash", { ...base, "messages/r_74.js": "1b", "runtime.js": "y" }, "other", /runtime\.js of catalog 'app' changed/],
    ["a generated file added", { ...base, "extra.js": "e" }, "r", /extra\.js was added to catalog 'app'/],
  ];
  for (const [label, files, runtime, expected] of cases) {
    const result = classify([snapshot(base)], [snapshot(files, runtime)]);
    if (expected instanceof RegExp) {
      assert.equal(result.kind, "reload", label);
      assert.match(result.reason, expected, label);
    } else assert.deepEqual(result, expected, label);
  }
  assert.match(classify([snapshot(base)], [snapshot(base, "r", "renamed")]).reason, /the catalogs changed/);
  // Dependency catalogs: several catalogs and their shared runtime.
  const grid = { ...base, "../runtime-core.js": "core" };
  assert.deepEqual(classify([snapshot(base), snapshot(grid, "r", "acme.grid")], [snapshot(base), snapshot({ ...grid, "messages/r_75.js": "x" }, "r", "acme.grid")]),
    { kind: "in-place", modules: ["/out/messages/r_75.js"] });
  assert.match(classify([snapshot(grid, "r", "acme.grid")], [snapshot({ ...grid, "../runtime-core.js": "core2" }, "r", "acme.grid")]).reason,
    /\.\.\/runtime-core\.js of catalog 'acme\.grid' changed/);
  assert.equal(withoutSourceHash(`export const a = 1;\nexport const sourceHash = "sha256:${"c".repeat(64)}";\nexport const b = 2;\n`), "export const a = 1;\nexport const b = 2;\n");
});

test("the transform makes a message module self-accepting only when its anchor occurs once", () => {
  const code = messageModule("title", { en: "Hello" });
  const accepting = selfAccepting(code);
  assert.ok(accepting.startsWith(code.slice(0, code.indexOf(messagesAnchor))));
  assert.ok(accepting.includes("let   messages = /* @__PURE__ */ (() => {"), "const becomes let with the line's columns kept");
  assert.equal(accepting.split("\n")[2].length, code.split("\n")[2].length);
  assert.match(accepting, /import \{ textChanged as __runicTextChanged \} from "virtual:runic-translations:hmr";/);
  assert.match(accepting, /import\.meta\.hot\.accept\(\);/);
  assert.equal(selfAccepting(code.replace(messagesAnchor, "const messages = (() => {")), undefined, "no anchor");
  assert.equal(selfAccepting(code + messagesAnchor + "})();\n"), undefined, "two anchors");
});

// Runs a transformed message module as Vite does one instance of it: a new instance per update, one hot.data per URL.
function instance(code, data, changed) {
  const body = code.replace(/^import .*$/gm, "").replaceAll("import.meta.hot", "hot").replace(/^export function (r_[0-9a-f]+)/m, "function $1");
  const name = /function (r_[0-9a-f]+)/.exec(body)[1];
  const hot = { data, accept() {} };
  const runtime = { freezeGeneratedText: (contract, locale, text) => ({ text }), formatMessage: (key, messages) => messages.en.text };
  return new Function("hot", "formatMessage", "freezeGeneratedText", "freezeGeneratedMessage", "freezeGeneratedPattern", "__runicTextChanged",
    `${body}\nreturn ${name};`)(hot, runtime.formatMessage, runtime.freezeGeneratedText, undefined, undefined, changed);
}

test("every instance of an updated message module formats the latest text", () => {
  const data = {}, changes = [];
  const first = instance(selfAccepting(messageModule("title", { en: "One" })), data, () => changes.push("first"));
  assert.equal(first(), "One");
  assert.deepEqual(changes, [], "the first instance reports nothing");
  // An update, and a chunk loaded later that imports this update's instance.
  const second = instance(selfAccepting(messageModule("title", { en: "Two" })), data, () => changes.push("second"));
  assert.deepEqual([first(), second()], ["Two", "Two"]);
  const third = instance(selfAccepting(messageModule("title", { en: "Three" })), data, () => changes.push("third"));
  assert.deepEqual([first(), second(), third()], ["Three", "Three", "Three"]);
  assert.deepEqual(changes, ["second", "third"], "each update reports one change");
});

test("hotUpdate updates an edited message in place in every environment and reloads structural changes once", async () => {
  const root = await mkdtemp(join(tmpdir(), "runic-vite-hmr-in-place-"));
  try {
    const { plugin, generated, manifest, logged, sent, module } = await devPlugin(root);
    const virtual = id => `\0virtual:runic-translations/app/${id}`;

    // Text: only the edited module, invalidated with the update's timestamp, in each environment.
    let targets = environments();
    await writeCatalog(generated, { messages: { title: { en: "Hi", de: "Hallo" }, other: { en: "Other", de: "Andere" } } });
    let { timestamp, results } = await save(plugin, manifest, targets);
    for (const [index, target] of targets.entries()) {
      assert.deepEqual(results[index].value.map(item => item.id), [module("title")], target.name);
      assert.deepEqual(target.invalidated, [{ id: module("title"), timestamp, isHmr: true }], `${target.name}: runtime.js, _index.js and the virtual modules stay`);
      assert.deepEqual(target.sent, [], target.name);
    }

    // The German text of another message.
    targets = environments();
    await writeCatalog(generated, { messages: { title: { en: "Hi", de: "Hallo" }, other: { en: "Other", de: "Weitere" } } });
    ({ results } = await save(plugin, manifest, targets));
    assert.deepEqual(results.map(result => result.value.map(item => item.id)), [[module("other")], [module("other")]]);

    // Declarations only (a comment in the JSDoc): nothing to update.
    targets = environments();
    await writeFile(join(generated, "messages.d.ts"), (await readFile(join(generated, "messages.d.ts"), "utf8")) + "// comment\n");
    const document = JSON.parse(await readFile(manifest, "utf8"));
    const declarations = document.assets.find(asset => asset.path === "messages.d.ts");
    const content = await readFile(join(generated, "messages.d.ts"));
    Object.assign(declarations, { sha256: sha256(content), byteLength: content.byteLength });
    await writeFile(manifest, JSON.stringify(document));
    ({ results } = await save(plugin, manifest, targets));
    assert.deepEqual(results.map(result => result.value), [[], []]);
    assert.deepEqual(targets.flatMap(target => target.invalidated), []);

    // A failed regeneration (the files do not match the manifest) is reported once and keeps the last good catalog;
    // the next good one is compared with it.
    targets = environments();
    await writeFile(module("title"), messageModule("title", { en: "Half written", de: "Hallo" }));
    ({ results } = await save(plugin, manifest, targets));
    assert.match(results[0].error.message, /integrity/);
    assert.deepEqual(results[1].value, []);
    await writeCatalog(generated, { messages: { title: { en: "Fixed", de: "Hallo" }, other: { en: "Other", de: "Weitere" } } });
    ({ results } = await save(plugin, manifest, targets));
    assert.deepEqual(results.map(result => result.value.map(item => item.id)), [[module("title")], [module("title")]]);

    // An added message reloads: everything is invalidated, each environment gets one full-reload, and the reason is logged once.
    targets = environments();
    await writeCatalog(generated, { messages: { title: { en: "Fixed", de: "Hallo" }, other: { en: "Other", de: "Weitere" }, added: { en: "New", de: "Neu" } } });
    ({ timestamp, results } = await save(plugin, manifest, targets));
    for (const [index, target] of targets.entries()) {
      assert.deepEqual(results[index].value, [], target.name);
      assert.deepEqual(target.sent, [{ type: "full-reload", path: "*" }], target.name);
      for (const id of [virtual("messages"), virtual("runtime"), module("title"), module("added"), join(dirname(module("title")), "_index.js")])
        assert.ok(target.invalidated.some(item => item.id === id && item.timestamp === timestamp), `${target.name}: ${id}`);
    }
    assert.deepEqual(sent, [], "the environments' own channels carry the reload");
    assert.deepEqual(logged.filter(line => line.includes("page reload")), ["[runic-translations] page reload: messages were added, removed or renamed in catalog 'app'"]);

    // A contract change reloads with its reason.
    targets = environments();
    await writeCatalog(generated, { messages: { title: { en: "Fixed", de: "Hallo" }, other: { en: "Other", de: "Weitere" }, added: { en: "New", de: "Neu" } }, contract: "markup changed" });
    ({ results } = await save(plugin, manifest, targets));
    assert.deepEqual(targets.map(target => target.sent.length), [1, 1]);
    assert.match(logged.at(-1), /page reload: dynamic\.js of catalog 'app' changed \(the catalog's contract changed\)/);

    // Without an environment hot channel (an older host), one full-reload goes through the server's.
    await writeCatalog(generated, { messages: { title: { en: "Fixed", de: "Hallo" } } });
    const bare = environments().map(target => ({ moduleGraph: target.moduleGraph }));
    await save(plugin, manifest, bare);
    assert.deepEqual(sent, [{ type: "full-reload", path: "*" }]);
  } finally { await rm(root, { recursive: true, force: true }); }
});

test("every environment gets each change when Vite handles changes of several files at once", async () => {
  const root = await mkdtemp(join(tmpdir(), "runic-vite-hmr-concurrent-"));
  try {
    const { plugin, generated, manifest, module } = await devPlugin(root);
    const [client, ssr] = environments();
    const call = (target, file, timestamp) => plugin.hotUpdate.call({ environment: target }, { type: "update", file, timestamp, modules: [], read: async () => "" });
    // Vite runs the environments of one file's change in turn, but the changes of two files concurrently: client A,
    // client B, then ssr A and ssr B.
    await writeCatalog(generated, { messages: { title: { en: "A", de: "Hallo" }, other: { en: "Other", de: "Andere" } } });
    const clientA = call(client, manifest, 1001);
    const runtime = join(generated, "runtime.js");
    const clientB = call(client, runtime, 1002);
    const [ssrA, ssrB] = [call(ssr, manifest, 1001), call(ssr, runtime, 1002)];
    const ids = async result => (await result).map(item => item.id);
    assert.deepEqual(await ids(clientA), [module("title")]);
    assert.deepEqual(await ids(ssrA), [module("title")], "the server environment gets the change it shares with the client");
    assert.deepEqual([await ids(clientB), await ids(ssrB)], [[], []], "the second file's regeneration found nothing new");
  } finally { await rm(root, { recursive: true, force: true }); }
});

test("a save the watcher dropped is reported again once the change is handled", async () => {
  const root = await mkdtemp(join(tmpdir(), "runic-vite-hmr-settle-"));
  try {
    const generated = join(root, "app.esm-v5");
    const manifest = await writeCatalog(generated, { messages: { title: { en: "Hello", de: "Hallo" } } });
    const plugin = runicTranslations({ manifest, typeDeclarations: false });
    plugin.configResolved({ logger: { info() {}, warn() {} }, mode: "development" });
    const watcher = new EventEmitter(), reported = [];
    watcher.add = () => {};
    watcher.on("change", path => reported.push(path));
    plugin.configureServer({ watcher, httpServer: new EventEmitter(), ws: { send() {} }, moduleGraph: environment("mixed").moduleGraph });
    await plugin.buildStart.call({ addWatchFile() {} });
    const settled = () => new Promise(resolveDelay => setTimeout(resolveDelay, 400));

    // A save the watcher reported, and nothing after it: no second report.
    await writeCatalog(generated, { messages: { title: { en: "One", de: "Hallo" } } });
    await save(plugin, manifest, environments());
    await settled();
    assert.deepEqual(reported, []);

    // A second save right after the first, which the watcher drops: reported again, once.
    await writeCatalog(generated, { messages: { title: { en: "Two", de: "Hallo" } } });
    const pending = save(plugin, manifest, environments());
    await writeCatalog(generated, { messages: { title: { en: "Three", de: "Hallo" } } });
    await pending;
    await settled();
    assert.deepEqual(reported, [manifest]);

    // A later event of the same file does its own check, so an earlier one does not report it twice.
    reported.length = 0;
    await writeCatalog(generated, { messages: { title: { en: "Four", de: "Hallo" } } });
    const earlier = save(plugin, manifest, environments());
    await writeCatalog(generated, { messages: { title: { en: "Five", de: "Hallo" } } });
    await Promise.all([earlier, save(plugin, manifest, environments())]);
    await settled();
    assert.deepEqual(reported, []);
  } finally { await rm(root, { recursive: true, force: true }); }
});

