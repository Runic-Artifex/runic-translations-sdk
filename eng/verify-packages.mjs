function quoted(value) {
  return value.replaceAll("&", "&amp;").replaceAll("\"", "&quot;").replaceAll("<", "&lt;");
}

function requireArchive(directory, name, version, extension) {
  const file = `${name.replace("@", "").replace("/", "-")}-${version}.${extension}`;
  const path = join(directory, file);
  assert.ok(existsSync(path), `Expected package candidate ${file}`);
  return path;
}

function consumerProject(name, version, { framework = "net10.0", wpf = false, build = false, extraPackages = [] } = {}) {
  return `<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><TargetFramework>${framework}</TargetFramework><OutputType>Exe</OutputType><ImplicitUsings>enable</ImplicitUsings><TreatWarningsAsErrors>true</TreatWarningsAsErrors>${wpf ? "<EnableWindowsTargeting>true</EnableWindowsTargeting><UseWPF>true</UseWPF>" : ""}</PropertyGroup><ItemGroup><PackageReference Include="${name}" Version="[${version}]"/>${build ? `<PackageReference Include="Runic.Translations" Version="[${version}]"/>` : ""}${extraPackages.map(([id, extra]) => `<PackageReference Include="${id}" Version="${extra}"/>`).join("")}</ItemGroup></Project>`;
}

function dotnetConsumer(directory, name, version, options, program, environment) {
  const consumer = join(directory, name.replaceAll(".", "-").toLowerCase());
  mkdirSync(consumer, { recursive: true });
  writeFileSync(join(consumer, "Consumer.csproj"), consumerProject(name, version, options));
  writeFileSync(join(consumer, "Program.cs"), program);
  const args = options.wpf
    ? ["build", "Consumer.csproj", "--configuration", "Release"]
    : ["run", "--project", "Consumer.csproj", "--configuration", "Release"];
  run("dotnet", args, consumer, environment);
}

// Vite warns on every dev start when a shipped sourcemap names sources the package omits.
function assertSelfContainedSourceMaps(name, directory) {
  const files = readdirSync(directory, { recursive: true, withFileTypes: true }).filter(entry => entry.isFile());
  for (const map of files.filter(entry => entry.name.endsWith(".map"))) {
    const path = join(map.parentPath, map.name);
    const { sources = [], sourcesContent = [], sourceRoot = "" } = JSON.parse(readFileSync(path, "utf8"));
    sources.forEach((source, index) => assert.ok(typeof sourcesContent[index] === "string" || existsSync(resolve(dirname(path), sourceRoot, source)),
      `${name}/${relative(directory, path)} points to the missing source ${source}`));
  }
}

function assertNoSourceReferences(directory) {
  const assets = JSON.parse(readFileSync(join(directory, "obj", "project.assets.json"), "utf8"));
  assert.ok(Object.values(assets.libraries).every(library => library.type !== "project"), "Consumer leaked a project reference");
}

// Version rule (T1g): code generated by release N runs on runtime N or later within the same minor before 1.0 (the same
// major from 1.0). A library packed with the last published release (its generator and runtime, from nuget.org) runs in an
// application on the candidate runtime, standalone and in a TranslationContext. After 0.9.0 ships, the baseline is 0.9.0,
// whose libraries depend on [0.9.0, 0.10.0-0): against a 0.10.0 candidate that is NU1608 by design, so this check then
// expects the warning (or runs only within one minor).
function verifyPreviousReleaseLibrary(directory, nuget, version, environment) {
  const previous = readFileSync(join(root, "eng/Versions.props"), "utf8").match(/<RunicTranslationsPackageValidationBaselineVersion>([^<]+)</)?.[1];
  assert.ok(previous, "eng/Versions.props has no RunicTranslationsPackageValidationBaselineVersion");
  const library = join(directory, "previous-release-library");
  const feed = join(directory, "previous-release-feed");
  mkdirSync(join(library, "translations"), { recursive: true });
  writeFileSync(join(library, "Library.csproj"), `<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><TargetFramework>net10.0</TargetFramework><PackageId>Acme.Grid</PackageId><Version>1.0.0</Version><TreatWarningsAsErrors>true</TreatWarningsAsErrors></PropertyGroup><ItemGroup><PackageReference Include="Runic.Translations" Version="${previous}"/><PackageReference Include="Runic.Translations.Build" Version="${previous}" PrivateAssets="all"/></ItemGroup></Project>`);
  writeFileSync(join(library, "translations", "runic.json"), JSON.stringify({
    schemaVersion: 1, catalog: "acme-grid", code: { namespace: "Acme.Grid", className: "GridText", visibility: "public" }, baseLocale: "en", locales: ["en", "de"],
  }));
  writeFileSync(join(library, "translations", "en.rmf2"), "title = Grid\nrows =\n  .input {$count :integer}\n  {{{$count} rows}}\n");
  writeFileSync(join(library, "translations", "de.rmf2"), "title = Raster\nrows =\n  .input {$count :integer}\n  {{{$count} Zeilen}}\n");
  // The published release comes from nuget.org only, never from the candidate feed.
  const published = join(directory, "previous-release.config");
  writeFileSync(published, `<?xml version="1.0" encoding="utf-8"?>
<configuration><packageSources><clear/><add key="nuget.org" value="https://api.nuget.org/v3/index.json"/></packageSources></configuration>`);
  run("dotnet", ["restore", "Library.csproj", "--configfile", published], library, environment);
  run("dotnet", ["pack", "Library.csproj", "--configuration", "Release", "--no-restore", "--output", feed], library, environment);

  const app = join(directory, "previous-release-app");
  mkdirSync(app);
  const config = join(directory, "previous-release-app.config");
  writeFileSync(config, `<?xml version="1.0" encoding="utf-8"?>
<configuration><packageSources><clear/><add key="candidate" value="${quoted(nuget)}"/><add key="library" value="${quoted(feed)}"/><add key="nuget.org" value="https://api.nuget.org/v3/index.json"/></packageSources><packageSourceMapping><clear/><packageSource key="candidate"><package pattern="Runic.Translations*"/></packageSource><packageSource key="library"><package pattern="Acme.*"/></packageSource><packageSource key="nuget.org"><package pattern="*"/></packageSource></packageSourceMapping></configuration>`);
  writeFileSync(join(app, "App.csproj"), `<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><TargetFramework>net10.0</TargetFramework><OutputType>Exe</OutputType><ImplicitUsings>enable</ImplicitUsings><TreatWarningsAsErrors>true</TreatWarningsAsErrors></PropertyGroup><ItemGroup><PackageReference Include="Runic.Translations" Version="[${version}]"/><PackageReference Include="Acme.Grid" Version="1.0.0"/></ItemGroup></Project>`);
  writeFileSync(join(app, "Program.cs"), `using Acme.Grid;
using Runic.Translations;

// A catalog generated before TranslationCatalogRegistration existed is registered from its generated members.
var registration = new TranslationCatalogRegistration(GridTextCatalog.CatalogId, GridTextCatalog.DefaultLocale,
    GridTextCatalog.ContractFingerprint, GridTextCatalog.Rmf2MarkupContract, GridTextCatalog.CreateProvider);
TranslationContext context = await TranslationContext.CreateBuilder().Add(registration).BuildAsync("de-AT");
var text = new GridText(context.GetManager(GridTextCatalog.CatalogId));
string german = text.Messages.title + "|" + text.Messages.rows(2) + "|" + context.Catalogs[0].LocaleResolution;
if (german != "Raster|2 Zeilen|Parent") throw new InvalidOperationException(german);
await context.SetLocaleAsync("en");
if (text.Messages.title != "Grid") throw new InvalidOperationException(text.Messages.title);
var standalone = new GridText(GridTextCatalog.CreateManager("de"));
if (standalone.Messages.title != "Raster") throw new InvalidOperationException(standalone.Messages.title);
Console.WriteLine("Library generated by ${previous} runs on runtime " + typeof(TranslationContext).Assembly.GetName().Version);
`);
  run("dotnet", ["restore", "App.csproj", "--configfile", config], app, environment);
  const restored = Object.keys(JSON.parse(readFileSync(join(app, "obj", "project.assets.json"), "utf8")).libraries)
    .filter(name => name.startsWith("Runic.Translations/"));
  assert.deepEqual(restored, [`Runic.Translations/${version}`], "the application must run the library on the candidate runtime");
  run("dotnet", ["run", "--project", "App.csproj", "--configuration", "Release", "--no-restore"], app, environment);
}

// Reads the root .nuspec of a .nupkg or .snupkg (a zip archive) through its central directory.
function packageNuspec(path) {
  const zip = readFileSync(path);
  let end = zip.length - 22;
  while (end >= 0 && zip.readUInt32LE(end) !== 0x06054b50) end--;
  assert.ok(end >= 0, `${path} is not a zip archive`);
  let offset = zip.readUInt32LE(end + 16);
  for (let index = zip.readUInt16LE(end + 10); index > 0; index--) {
    const method = zip.readUInt16LE(offset + 10), size = zip.readUInt32LE(offset + 20);
    const nameLength = zip.readUInt16LE(offset + 28), extraLength = zip.readUInt16LE(offset + 30), commentLength = zip.readUInt16LE(offset + 32);
    const local = zip.readUInt32LE(offset + 42);
    const name = zip.toString("utf8", offset + 46, offset + 46 + nameLength);
    if (!name.includes("/") && name.endsWith(".nuspec")) {
      const start = local + 30 + zip.readUInt16LE(local + 26) + zip.readUInt16LE(local + 28);
      const data = zip.subarray(start, start + size);
      return (method === 8 ? inflateRawSync(data) : data).toString("utf8");
    }
    offset += 46 + nameLength + extraLength + commentLength;
  }
  assert.fail(`${path} has no .nuspec`);
}

// Version rule (T1g): a library packed with the candidate Build package depends on Runic.Translations [N, next minor-0)
// before 1.0 ([N, next major-0) from 1.0). A multi-targeted library generates its .nuspec in the outer build, which
// imports the Build package's buildMultiTargeting targets; the symbol package carries the same range.
function verifyMultiTargetedLibrary(directory, version, environment) {
  const library = join(directory, "multi-targeted-library");
  const output = join(library, "packages");
  mkdirSync(join(library, "translations"), { recursive: true });
  writeFileSync(join(library, "Library.csproj"), `<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><TargetFrameworks>net10.0;net10.0-windows</TargetFrameworks><EnableWindowsTargeting>true</EnableWindowsTargeting><PackageId>Acme.Toolbar</PackageId><Version>1.0.0</Version><TreatWarningsAsErrors>true</TreatWarningsAsErrors><IncludeSymbols>true</IncludeSymbols><SymbolPackageFormat>snupkg</SymbolPackageFormat></PropertyGroup><ItemGroup><PackageReference Include="Runic.Translations" Version="${version}"/><PackageReference Include="Runic.Translations.Build" Version="${version}" PrivateAssets="all"/></ItemGroup></Project>`);
  writeFileSync(join(library, "translations", "runic.json"), JSON.stringify({
    schemaVersion: 1, catalog: "acme-toolbar", code: { namespace: "Acme.Toolbar", className: "ToolbarText", visibility: "public" }, baseLocale: "en", locales: ["en"],
  }));
  writeFileSync(join(library, "translations", "en.rmf2"), "save = Save\n");
  run("dotnet", ["pack", "Library.csproj", "--configuration", "Release", "--output", output], library, environment);
  const [major, minor] = version.split(/[.+-]/).map(Number);
  const range = `[${version}, ${major === 0 ? `0.${minor + 1}.0-0` : `${major + 1}.0.0-0`})`;
  for (const file of ["Acme.Toolbar.1.0.0.nupkg", "Acme.Toolbar.1.0.0.snupkg"]) {
    const ranges = [...packageNuspec(join(output, file)).matchAll(/<dependency id="Runic\.Translations" version="([^"]*)"/g)].map(match => match[1]);
    assert.deepEqual(ranges, [range, range], `${file} requires Runic.Translations ${range} for both target frameworks`);
  }
}

