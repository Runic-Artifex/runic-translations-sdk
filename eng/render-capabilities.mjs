import { readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const matrixPath = resolve(root, "specs/translations/capabilities-v1.json");
const documentationPath = resolve(
  root,
  "docs/guides/translations/capabilities.md",
);
const check = process.argv.slice(2).includes("--check");

if (process.argv.length > (check ? 3 : 2))
  throw new Error("Usage: bun eng/render-capabilities.mjs [--check]");

const matrix = JSON.parse(await readFile(matrixPath, "utf8"));
const mark = (value) => (value ? "yes" : "—");
const inline = (value) => `\`${value}\``;
const table = (headers, alignment, rows) => {
  const widths = headers.map((header, index) =>
    Math.max(header.length, ...rows.map((row) => row[index].length)),
  );
  const cell = (value, index) =>
    alignment[index] === "right"
      ? value.padStart(widths[index])
      : value.padEnd(widths[index]);
  const separator = (width, index) =>
    alignment[index] === "right"
      ? `${"-".repeat(Math.max(1, width - 1))}:`
      : "-".repeat(width);
  return [
    `| ${headers.map(cell).join(" | ")} |`,
    `| ${widths.map(separator).join(" | ")} |`,
    ...rows.map((row) => `| ${row.map(cell).join(" | ")} |`),
  ];
};

const localeRows = matrix.locales.map((locale) => [
  inline(locale.tag),
  mark(locale.cardinal),
  mark(locale.ordinal),
  mark(locale.relativeTime),
  mark(locale.list),
]);
const formatterRows = [];
for (const [formatter, forms] of Object.entries(matrix.formatterProfile)) {
  const grouped = new Map();
  for (const [form, equivalence] of Object.entries(forms)) {
    const names = grouped.get(equivalence) ?? [];
    names.push(form);
    grouped.set(equivalence, names);
  }
  for (const [equivalence, names] of grouped)
    formatterRows.push([
      inline(formatter),
      names.map(inline).join(", "),
      equivalence,
    ]);
}

const lines = [
  "# Locale and formatter capabilities",
  "",
  "> Generated from `specs/translations/capabilities-v1.json`; do not edit this file directly.",
  "",
  `Capability matrix version: **${matrix.capabilityMatrixVersion}**\\`,
  `Release target: **${matrix.releaseTarget}**\\`,
  `CLDR source: **${matrix.cldr.version}** (JSON tag \`${matrix.cldr.jsonTag}\`, ${matrix.cldr.license})\\`,
  `Conforming backends: **${matrix.backends.join(", ")}**`,
  "",
  "## Locale selectors, relative time and lists",
  "",
  ...table(
    ["Locale", "Cardinal", "Ordinal", "Relative time", "List"],
    ["left", "right", "right", "right", "right"],
    localeRows,
  ),
  "",
  "The table lists every CLDR language and script locale. A regional or script variant such as `de-CH`, `pt-AO` or `zh-TW` has the capabilities of the locale it resolves to:",
  "its CLDR data ID adds the likely script (`zh-TW` is `zh-Hant-TW`), plural rules are looked up by removing subtags (`pt-PT` has its own rules, `pt-AO` uses `pt`'s),",
  "and list patterns and relative time follow CLDR's parent locales (`pt-AO` uses `pt-PT`'s, `es-MX` uses `es-419`'s).",
  "A language without CLDR ordinal rules selects `other` for every ordinal, and a locale with CLDR data but no plural rules of its own (`agq`, `rw`, `mi`) selects `other` for every number (CLDR's root rule).",
  "Only languages without CLDR data, such as `tlh`, fail compilation with `RTR0031` when a message selects on plurals or formats a list or relative time.",
  `Cardinal selector equivalence: **${matrix.messageProfile.cardinal}**.`,
  `Ordinal selector equivalence: **${matrix.messageProfile.ordinal}**.`,
  `Relative-time equivalence: **${matrix.messageProfile.relativeTime}**.`,
  `List equivalence: **${matrix.messageProfile.list}**.`,
  "Plural selection, relative-time and list patterns are generated from the pinned CLDR subset; the ESM backend does not delegate them to host `Intl` data.",
  "Relative time formats its number as `:number` does by default, from the pinned CLDR number formats (symbols, grouping and digits), so it is exact too.",
  "Numbers and percentages use the pinned CLDR number formats of the formatting locale in both backends; localized dates and times use platform data, so they stay semantic.",
  "Cardinal and ordinal rules use all CLDR operands of the displayed number, after percent scaling, rounding and minimum fraction digits.",
  "",
  "## Formatter equivalence",
  "",
  ...table(
    ["Formatter", "Forms", "Equivalence"],
    ["left", "left", "left"],
    formatterRows,
  ),
  "",
  `**Exact:** ${matrix.equivalence.exact}`,
  "",
  `**Semantic:** ${matrix.equivalence.semantic}`,
  "",
  "This release deliberately claims only the locales above.",
  "A platform may recognize other BCP 47 tags for scalar formatting, but they are",
  "not part of the cross-runtime support promise until they appear in the matrix",
  "and shared .NET/ESM conformance fixtures.",
  "",
];
const rendered = lines.join("\n");

if (check) {
  const current = await readFile(documentationPath, "utf8").catch(() => "");
  if (current !== rendered)
    throw new Error(
      `${relative(root, documentationPath)} is stale; run bun eng/render-capabilities.mjs`,
    );
} else {
  await writeFile(documentationPath, rendered, "utf8");
}
