    private static void ReadableEqualsEncoded()
    {
        string title = Path("application", "title"), greeting = Path("greeting"), badge = Path("profile", "badge");
        string items = Path("cart", "items"), help = Path("checkout", "help");
        string userName = Encoded("user-name");
        string source = $$"""
            namespace Example.Consumer;
            using System;
            using System.Collections.Generic;
            using Example.Translations;
            using Runic.Translations;

            public static class Probe
            {
                public static string Run()
                {
                    ITranslationManager manager = AppTextCatalog.CreateManagerAsync("en").AsTask().GetAwaiter().GetResult();
                    var text = new AppText(manager);
                    var renderer = new Rmf2InlineRenderer(AppTextCatalog.Rmf2MarkupContract);
                    var guide = new InlineLinkBinding(new Uri("https://example.test/guide"));
                    var retry = new InlineActionBinding(() => { });
                    var output = new List<string>();
                    foreach (string locale in new[] { "en", "de" })
                    {
                        manager.SetLocaleAsync(locale).AsTask().GetAwaiter().GetResult();
                        Require(ReferenceEquals(text.Messages, text.Messages), "facade is cached");
                        Require(text.Messages.application_title == text.{{title}}, "title");
                        Require(text.Messages.greeting(name: "Ada") == text.{{greeting}}(Ada()), "greeting");
                        Require(text.Messages.profile_badge({{userName}}: "ada") == text.{{badge}}("ada"), "badge");
                        Require(text.Messages.cart_items(count: 3) == text.{{items}}(3), "items");
                        LocalizedTextContent<AppTextSlots.checkout_help> content = text.Messages.checkout_help;
                        BoundLocalizedTextContent bound = content.Bind(new(guide: guide, retry: retry));
                        var slots = new Dictionary<string, InlineMarkupBinding> { ["guide"] = guide, ["retry"] = retry };
                        string typed = renderer.ToPlainText(bound, allowActionLabels: true);
                        Require(typed == renderer.ToPlainText("checkout_help", text.{{help}}, slots, allowActionLabels: true), "help");
                        LocalizedTextContent untyped = content;
                        Require(untyped.Locale == locale && content.Locale == locale, "content locale");
                        output.Add(text.Messages.greeting(name: "Ada") + "|" + text.Messages.profile_badge({{userName}}: "ada") + "|" +
                            text.Messages.cart_items(count: 1) + "|" + typed);
